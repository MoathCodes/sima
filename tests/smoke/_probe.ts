import { chromium } from 'playwright-core';
import { homedir } from 'node:os';
const exe = `${homedir()}/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome`;
const browser = await chromium.launch({ executablePath: exe, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
await ctx.addInitScript(() => { localStorage.setItem('sima-intro', '1'); localStorage.setItem('sima-view', 'expert'); localStorage.setItem('sima-guide', JSON.stringify({ tips: ['measure-words'] })); });
const page = await ctx.newPage();
await page.goto('http://localhost:5186/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('html[data-ready]', { state: 'attached' });
await page.waitForTimeout(6000);
await page.mouse.move(1366 * 0.2, 768 * 0.55);
await page.mouse.wheel(0, -240);
await page.waitForTimeout(3000);
const info = () => page.evaluate(() => ({ patch: document.querySelector('#sky')?.getAttribute('data-patch'), frame: JSON.stringify(document.getElementById('frame')!.getBoundingClientRect()) }));
console.log('measure open', await info());
await page.click('[data-guide="measure"]');
await page.waitForTimeout(1500);
console.log('measure closed', await info());
await browser.close();
